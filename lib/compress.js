// 四层压缩管线的纯函数部分（0.5.11）
// ------------------------------------------------------------------
// 为什么单独一个文件：分层压缩的每一层都必须是「可单测的纯变换」，
// 这样离线测试不需要宿主、不调 LLM、不联网，也能验证每层的逆变换。
// 文件读写 / 记忆库同步 / 谱系落盘 全在 lib/index.js 里做（这一层不碰 fs）。
//
// 分层：
//   L1 无损折叠：连续重复行 ≥3 → 折叠成一行标记，逆变换可精确还原
//   L2 落盘：单条超大内容存盘，上下文留头 + 尾 + 路径 + SHA256
//   L3 软压力：70% 只提醒（不改内容）/ 80% 起按优先级驱逐可重放内容
//   L4 LLM 摘要：只在到达摘要阈值时、且调用方注入摘要器时才跑；预算预留、摘要前全量存档
import { createHash } from 'node:crypto';

/** UTF-8 字节数 */
export const 字节 = (s) => Buffer.byteLength(String(s ?? ''), 'utf8');

/** 四层名字（谱系/报告里统一用这几个词） */
export const 层 = Object.freeze({
  折叠: 'L1 无损折叠',
  落盘: 'L2 落盘',
  软压力: 'L3 软压力',
  摘要: 'L4 LLM 摘要',
});

/** 软压力线：70% 提醒，80% 驱逐（与自动压缩阈值一致） */
export const 软压力线 = Object.freeze({ 提醒: 0.7, 驱逐: 0.8 });
/** 摘要触发线：只有到 90% 且前面几层都没压下来，才考虑 LLM 摘要 */
export const 摘要线 = 0.9;

const 边界截断 = (文本, 上限字节) => {
  if (字节(文本) <= 上限字节) return 文本;
  let 出 = '';
  let 计 = 0;
  for (const 字 of 文本) {
    const b = 字节(字);
    if (计 + b > 上限字节) break;
    出 += 字;
    计 += b;
  }
  return 出;
};
const 边界截尾 = (文本, 上限字节) => {
  if (字节(文本) <= 上限字节) return 文本;
  const 字们 = [...文本];
  let 出 = '';
  let 计 = 0;
  for (let i = 字们.length - 1; i >= 0; i--) {
    const b = 字节(字们[i]);
    if (计 + b > 上限字节) break;
    出 = 字们[i] + 出;
    计 += b;
  }
  return 出;
};

// ── L1 无损折叠 ────────────────────────────────────────────────────────────
// 折叠的是「连续空行 / 重复行」这类纯冗余：一条记忆里贴进来的日志、表格分隔线、
// 大段重复的占位符。折叠后留一行标记，标记里带 fold 序号；逆变换记录原行与次数，
// 所以「文本 → 折叠 → 还原」必须得到逐字节相同的原文。
// 令牌带原行短指纹：不同条目的折叠记录拼在一起也能唯一还原（行前缀相同也不会串）
const 折叠令牌 = (k, 行) => `⟦dsh-fold-${k}-${createHash('sha1').update(String(行)).digest('hex').slice(0, 8)}⟧`;

/** 生成折叠标记行（恢复时按整行匹配） */
export function 折叠标记行(k, 行, 次, 存档 = '') {
  const 摘要 = 边界截断(String(行).trim(), 36);
  return `……${折叠令牌(k, 行)}（同一行重复 ×${次}，已无损折叠；原行「${摘要}」${存档 ? `，逆变换见 ${存档}/逆变换.json` : ''}）`;
}

/**
 * 无损折叠连续重复行（≥ 最少重复 次）。
 * @returns {{文本:string, 逆变换:Array, 省下:number}}
 */
export function 折叠重复行(文本, { 最少重复 = 3, 存档 = '' } = {}) {
  const 原 = String(文本 ?? '');
  const 行们 = 原.split('\n');
  const 出 = [];
  const 逆变换 = [];
  for (let i = 0; i < 行们.length;) {
    const 行 = 行们[i];
    let j = i + 1;
    while (j < 行们.length && 行们[j] === 行) j++;
    const 次 = j - i;
    // 只折叠有内容的行；空行由 § 拆分/投影已经处理，折叠空行反而会破坏格式
    if (次 >= 最少重复 && 行.trim()) {
      const k = 逆变换.length + 1;
      const 标记 = 折叠标记行(k, 行, 次, 存档);
      // 只有真省字节才折，否则保留原文（短行重复折叠会变长）
      const 省 = 字节(行) * 次 - 字节(标记);
      if (省 > 0) {
        逆变换.push({ k, 标记, 行, 次数: 次 });
        出.push(标记);
        i = j;
        continue;
      }
    }
    出.push(行);
    i++;
  }
  const 新文本 = 出.join('\n');
  return { 文本: 新文本, 逆变换, 省下: Math.max(0, 字节(原) - 字节(新文本)) };
}

/** L1 逆变换：把折叠标记行展开回原来的 N 行（不依赖磁盘，纯内存可恢复） */
export function 还原折叠(文本, 逆变换 = []) {
  const 表 = new Map((逆变换 || []).map((r) => [r.标记, r]));
  const 出 = [];
  for (const 行 of String(文本 ?? '').split('\n')) {
    const r = 表.get(行);
    if (r) for (let k = 0; k < r.次数; k++) 出.push(r.行);
    else 出.push(行);
  }
  return 出.join('\n');
}

// ── L2 落盘 ────────────────────────────────────────────────────────────────
/**
 * 单条内容超过阈值就落盘：上下文里只留头 + 尾 + 路径 + SHA256。
 * 落盘文件由调用方写入（这里只算替换文本，保证可离线测试）。
 * @returns {{触发:boolean, 文本:string, sha256:string, 原字节:number, 头字节:number, 尾字节:number, 省下:number}}
 */
export function 落盘超大(文本, { 路径 = '', 阈值 = 4000, 头部 = 480, 尾部 = 160 } = {}) {
  const 原 = String(文本 ?? '');
  const 原字节 = 字节(原);
  const 空 = { 触发: false, 文本: 原, sha256: '', 原字节, 头字节: 0, 尾字节: 0, 省下: 0 };
  if (原字节 <= 阈值) return 空;
  const 头 = 边界截断(原, 头部);
  const 尾 = 边界截尾(原, 尾部);
  const sha256 = createHash('sha256').update(原).digest('hex');
  const 中略 = Math.max(0, 原字节 - 字节(头) - 字节(尾));
  const 替换 = [
    头,
    `……（中略 ${中略} 字节；全文已落盘 ${路径 || '(未指定路径)'}；sha256 ${sha256}；可恢复）……`,
    尾,
  ].join('\n');
  if (字节(替换) >= 原字节) return 空;
  return { 触发: true, 文本: 替换, sha256, 原字节, 头字节: 字节(头), 尾字节: 字节(尾), 省下: 原字节 - 字节(替换) };
}

/** 校验落盘内容是否与谱系里的 SHA256 一致（防止存档被改/截断） */
export function 校验落盘(内容, sha256) {
  return !!sha256 && createHash('sha256').update(String(内容 ?? '')).digest('hex') === sha256;
}

// ── L3 软压力 ──────────────────────────────────────────────────────────────
/** 当前用量属于哪一档：ok(<70%) / 提醒(70%~80%) / 驱逐(≥80%) */
export function 软压力量级(用量字节, 限) {
  const 比 = 限 > 0 ? 用量字节 / 限 : 0;
  const 百分比 = Math.round(比 * 100);
  if (比 >= 软压力线.驱逐) {
    return {
      级别: '驱逐',
      百分比,
      提示: `已用 ${百分比}%（${用量字节}/${限} 字节）→ 到 ${Math.round(软压力线.驱逐 * 100)}% 驱逐线：按优先级驱逐可重放内容（全文都进 archived/）`,
    };
  }
  if (比 >= 软压力线.提醒) {
    return {
      级别: '提醒',
      百分比,
      提示: `已用 ${百分比}%（${用量字节}/${限} 字节）→ 过 ${Math.round(软压力线.提醒 * 100)}% 软压力线：建议先归档/折叠；到 ${Math.round(软压力线.驱逐 * 100)}% 会自动驱逐可重放内容（这一步不删原文）`,
    };
  }
  return { 级别: 'ok', 百分比, 提示: '' };
}

/**
 * 可驱逐优先级：数字越小越先驱逐；Infinity 表示这层不动它。
 *   0 = 临时/进度类（判定词在 index.js，和体检共用）
 *   1 = 可重放指针（已落盘/已归档，正文能从 archived/ 原样取回）
 *   2 = 超长条目（压缩后整份存档里仍有全文，算「可重放」）
 */
export function 驱逐优先级(文本, { 临时 = false, 长条字节 = 320 } = {}) {
  const t = String(文本 ?? '');
  if (临时) return 0;
  if (/全文已落盘|全文见 archived|sha256 [0-9a-f]{16}/.test(t)) return 1;
  if (字节(t) > 长条字节) return 2;
  return Infinity;
}

// ── L4 LLM 摘要 ────────────────────────────────────────────────────────────
/** 摘要预算：摘要正文最多占上限的 15%，且给后续写入留同样多的余量 */
export function 摘要预算(限, 比例 = 0.15) {
  const 预留 = Math.max(128, Math.floor(限 * 比例));
  return { 预留, 摘要上限: 预留 };
}

/** 摘要结果按字节边界截断到预算内 */
export function 截断到预算(文本, 上限字节) {
  const 原 = String(文本 ?? '');
  if (字节(原) <= 上限字节) return 原;
  return 边界截断(原, Math.max(0, 上限字节 - 字节('…'))) + '…';
}
